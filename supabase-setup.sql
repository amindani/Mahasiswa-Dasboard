-- 1) Buat bucket bernama materi-tugas melalui Storage dan aktifkan Public bucket.
-- 2) Matikan pendaftaran publik, lalu buat satu akun admin secara manual di Authentication > Users.
-- 3) Jalankan SQL ini di SQL Editor.
create table if not exists public.documents (
 id bigint generated by default as identity primary key,
 file_name text not null,
 storage_path text not null unique,
 file_size bigint not null default 0,
 mime_type text,
 category text not null default 'Materi Kuliah',
 description text not null default '',
 uploaded_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now()
);
alter table public.documents enable row level security;
drop policy if exists "Public can read document metadata" on public.documents;
create policy "Public can read document metadata" on public.documents for select to anon, authenticated using (true);
drop policy if exists "Logged in admin can insert document metadata" on public.documents;
create policy "Logged in admin can insert document metadata" on public.documents for insert to authenticated with check (auth.uid() = uploaded_by);
drop policy if exists "Uploader can delete document metadata" on public.documents;
create policy "Uploader can delete document metadata" on public.documents for delete to authenticated using (auth.uid() = uploaded_by);
drop policy if exists "Logged in admin can upload to academic bucket" on storage.objects;
create policy "Logged in admin can upload to academic bucket" on storage.objects for insert to authenticated with check (bucket_id = 'materi-tugas');
drop policy if exists "Logged in admin can delete from academic bucket" on storage.objects;
create policy "Logged in admin can delete from academic bucket" on storage.objects for delete to authenticated using (bucket_id = 'materi-tugas');
-- Kebijakan upload berlaku untuk user Auth yang ada. Nonaktifkan sign-up publik dan hanya buat akun admin.
